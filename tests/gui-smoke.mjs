import {createRequire} from 'node:module';
import {mkdir,writeFile,readFile} from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
const require=createRequire(path.resolve('work/qa/package.json'));
const {chromium}=require('playwright');
const browser=await chromium.connectOverCDP(process.env.WALLPAPER_CDP||'http://127.0.0.1:32222');
const pages=browser.contexts().flatMap(c=>c.pages());
const page=pages.find(p=>p.url().includes('manager.wallpaper.local'));
assert.ok(page,'manager window loaded');
await page.waitForSelector('.card');
assert.equal(await page.title(),'Wallpaper Desktop');
const consoleErrors=[];
page.on('pageerror',error=>consoleErrors.push(error.message));
await mkdir('work/validation',{recursive:true});
await page.screenshot({path:'work/validation/manager.png'});
assert.ok((await page.locator('.card').count())>=2);
await page.locator('#search').fill('不存在');
await assert.equal(await page.locator('.card').count(),0);
await page.locator('#search').fill('');
await page.locator('.card').filter({hasText:'极光'}).click();
const expectedWeb=await page.locator('.card.selected').getAttribute('data-id');
const previousWindow=(await page.evaluate(()=>window.wallpaper.call('diagnostics'))).windows[0]?.hwnd||0;
await page.locator('#apply').click();
await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('正在播放'));
await page.waitForFunction(async({id,previous})=>{const d=await window.wallpaper.call('diagnostics');return d.windows.length===1&&d.windows[0].ready&&d.windows[0].id===id&&d.windows[0].hwnd!==previous},{id:expectedWeb,previous:previousWindow});
const diag=await page.evaluate(()=>window.wallpaper.call('diagnostics'));
assert.equal(diag.windows.length,1);
assert.ok(diag.windows[0].parent>0);
assert.equal(diag.windows[0].parent,diag.windows[0].host);
assert.equal(diag.windows[0].attached,true);
await writeFile('work/validation/desktop.json',JSON.stringify(diag,null,2));
const playerBrowser=await chromium.connectOverCDP(process.env.WALLPAPER_PLAYER_CDP||'http://127.0.0.1:32223');
let webPage;
for(let i=0;i<50&&!webPage;i++){webPage=playerBrowser.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('content.wallpaper.local'));if(!webPage)await new Promise(r=>setTimeout(r,100));}
assert.ok(webPage,'web renderer created');
await webPage.waitForFunction(()=>window.animationFrames>10);
await webPage.screenshot({path:'work/validation/web.png'});
const initialFrames=await webPage.evaluate(()=>window.animationFrames);
await page.locator('#pause').click();
await page.waitForFunction(()=>document.querySelector('#status').textContent.includes('暂停'));
await page.evaluate(()=>window.wallpaper.call('settings',{volume:30,muted:true,fit:'cover',pauseOnFullscreen:true,intervalSeconds:300}));
assert.equal((await page.evaluate(()=>window.wallpaper.call('diagnostics'))).windows[0].audioMuted,true);
const frozenA=(await page.evaluate(()=>window.wallpaper.call('diagnostics'))).windows[0].pauseFrameHash;
assert.ok(frozenA,'native paused frame retained');
await new Promise(r=>setTimeout(r,250));
const frozenB=(await page.evaluate(()=>window.wallpaper.call('diagnostics'))).windows[0].pauseFrameHash;
assert.equal(frozenA,frozenB,'native paused frame unchanged');
assert.equal((await page.evaluate(()=>window.wallpaper.call('diagnostics'))).windows[0].suspended,true);
await page.locator('#pause').click();
await webPage.waitForFunction(n=>window.animationFrames>n+3,initialFrames);
await page.evaluate(()=>Promise.all([window.wallpaper.call('pause'),window.wallpaper.call('pause')]));
await webPage.waitForFunction(n=>window.animationFrames>n+10,initialFrames);
await page.locator('#addPlaylist').click();
await page.waitForSelector('#playlistItems button');
await page.locator('#settings').click();
await page.locator('#volume').evaluate(el=>{el.value='42';el.dispatchEvent(new Event('input',{bubbles:true}))});
await page.locator('#muted').uncheck();
await page.locator('#saveSettings').click();
await page.waitForFunction(()=>!document.querySelector('#settingsDialog').open);
const state=(await page.evaluate(()=>window.wallpaper.call('state'))).state;
assert.equal(state.settings.volume,42);
assert.equal(state.settings.muted,false);
assert.equal((await page.evaluate(()=>window.wallpaper.call('diagnostics'))).windows[0].audioMuted,false);
await page.locator('#settings').click();
await page.screenshot({path:'work/validation/settings.png'});
await page.locator('#cancelSettings').click();
const video=state.items.find(x=>x.kind==='video');
if (video) {
  await page.evaluate(id=>window.wallpaper.call('apply',{id,monitor:document.querySelector('#monitor').value}),video.id);
  let target;
  for(let i=0;i<50&&!target;i++){target=playerBrowser.contexts().flatMap(c=>c.pages()).find(p=>p.url().includes('player.wallpaper.local'));if(!target)await new Promise(r=>setTimeout(r,100));}
  assert.ok(target,'video renderer created');
  await target.waitForFunction(()=>document.querySelector('video')?.currentTime>1,{},{timeout:20000});
  const timing=await target.evaluate(()=>({time:document.querySelector('video').currentTime,width:document.querySelector('video').videoWidth}));
  assert.ok(timing.width>0);
  await writeFile('work/validation/video.json',JSON.stringify(timing));
  await target.screenshot({path:'work/validation/video.png'});
  await page.locator('#pause').click();
  await target.waitForFunction(()=>document.querySelector('video').paused);
  await page.locator('#pause').click();
  await target.waitForFunction(()=>!document.querySelector('video').paused);
}
await page.locator('#stop').click();
await page.waitForFunction(()=>document.querySelector('#status').textContent==='尚未播放');
assert.equal((await page.evaluate(()=>window.wallpaper.call('diagnostics'))).windows.length,0);
await page.reload();
await page.waitForSelector('.card');
assert.equal((await page.evaluate(()=>window.wallpaper.call('state'))).state.settings.volume,42);
const monitor=state.monitors[0].id;
const webId=state.items.find(x=>x.kind==='web').id;
await page.evaluate(async({id,monitor})=>{await Promise.allSettled([window.wallpaper.call('apply',{id,monitor}),window.wallpaper.call('stop',{monitor})]);},{id:webId,monitor});
assert.equal((await page.evaluate(()=>window.wallpaper.call('diagnostics'))).windows.length,0,'stop cancels pending renderer initialization');
if(video){
  await page.evaluate(async({web,video,monitor})=>{await Promise.allSettled([window.wallpaper.call('apply',{id:web,monitor}),window.wallpaper.call('apply',{id:video,monitor})]);},{web:webId,video:video.id,monitor});
  assert.equal((await page.evaluate(()=>window.wallpaper.call('diagnostics'))).windows[0].id,video.id,'newest apply wins');
  await page.evaluate(monitor=>window.wallpaper.call('stop',{monitor}),monitor);
}
console.log('PASS: native WebView2 UI, search, desktop attachment, actual web suspension, rapid resume, native mute, playlist, settings, reload, stop cancellation and newest apply');
assert.deepEqual(consoleErrors,[],'no manager JavaScript runtime errors');
await playerBrowser.close();
await browser.close();
